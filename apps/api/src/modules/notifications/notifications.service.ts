import { ForbiddenException, Injectable } from '@nestjs/common';
import { PrismaService } from '../../database/prisma.service.js';

export interface BusinessNotification {
  id: string;
  actionCode: string;
  entityType: string;
  entityId: string;
  dossierId: string | null;
  occurredAt: Date;
  title: string;
  message: string;
}

@Injectable()
export class NotificationsService {
  constructor(private readonly prisma: PrismaService) {}

  async listMine(authUserId: string, limit = 30): Promise<BusinessNotification[]> {
    const user = await this.prisma.utilisateur.findUnique({
      where: { authUserId },
      select: { idUtilisateur: true, etatCompte: true },
    });
    if (!user || user.etatCompte !== 'ACTIF') {
      throw new ForbiddenException('Un compte actif est requis pour consulter les notifications.');
    }

    const query = [
      'SELECT',
      '  event.id,',
      '  event.action_code AS "actionCode",',
      '  event.entity_type AS "entityType",',
      '  event.entity_id AS "entityId",',
      '  event.dossier_id AS "dossierId",',
      '  event.occurred_at AS "occurredAt",',
      "  CASE event.action_code",
      "    WHEN 'SIGNALEMENT_SOUMIS' THEN 'Nouveau signalement'",
      "    WHEN 'DEMANDE_COMPLEMENT_CREEE' THEN 'Informations complémentaires demandées'",
      "    WHEN 'DEMANDE_COMPLEMENT_REPONDUE' THEN 'Complément transmis'",
      "    WHEN 'SIGNALEMENT_QUALIFIE' THEN 'Signalement qualifié'",
      "    WHEN 'SIGNALEMENT_REJETE' THEN 'Signalement rejeté'",
      "    WHEN 'DOSSIER_CREE' THEN 'Nouveau dossier de traitement'",
      "    WHEN 'AFFECTATION_CREEE' THEN 'Nouvelle affectation'",
      "    WHEN 'AFFECTATION_ACCEPTEE' THEN 'Affectation acceptée'",
      "    WHEN 'AFFECTATION_REFUSEE' THEN 'Affectation refusée'",
      "    WHEN 'AFFECTATION_REAFFECTEE' THEN 'Affectation réorganisée'",
      "    WHEN 'INTERVENTION_SOUMISE' THEN 'Compte rendu transmis'",
      "    WHEN 'VERIFICATION_CONFORME' THEN 'Intervention validée'",
      "    WHEN 'VERIFICATION_REPRISE' THEN 'Reprise demandée'",
      "    WHEN 'DOSSIER_CLOTURE' THEN 'Dossier clôturé'",
      "    WHEN 'DOSSIER_PRIORITE_MODIFIEE' THEN 'Priorité du dossier modifiée'",
      "    WHEN 'DOSSIER_LOCALISATION_MODIFIEE' THEN 'Localisation du dossier modifiée'",
      "    ELSE 'Mise à jour métier'",
      '  END AS title,',
      '  CASE event.action_code',
      "    WHEN 'SIGNALEMENT_SOUMIS' THEN 'Votre signalement a bien été transmis.'",
      "    WHEN 'DEMANDE_COMPLEMENT_CREEE' THEN 'Une information complémentaire est attendue pour votre signalement.'",
      "    WHEN 'DEMANDE_COMPLEMENT_REPONDUE' THEN 'Un citoyen a répondu à une demande de complément.'",
      "    WHEN 'SIGNALEMENT_QUALIFIE' THEN 'Votre signalement a été qualifié.'",
      "    WHEN 'SIGNALEMENT_REJETE' THEN 'Une décision a été prise sur votre signalement.'",
      "    WHEN 'DOSSIER_CREE' THEN 'Un dossier est disponible pour affectation.'",
      "    WHEN 'AFFECTATION_CREEE' THEN 'Une mission a été affectée à votre équipe.'",
      "    WHEN 'AFFECTATION_ACCEPTEE' THEN 'Une équipe a accepté une mission.'",
      "    WHEN 'AFFECTATION_REFUSEE' THEN 'Une équipe n’a pas pu accepter une mission.'",
      "    WHEN 'AFFECTATION_REAFFECTEE' THEN 'Une affectation a été modifiée.'",
      "    WHEN 'INTERVENTION_SOUMISE' THEN 'Un compte rendu attend une vérification indépendante.'",
      "    WHEN 'VERIFICATION_CONFORME' THEN 'Votre intervention a été déclarée conforme.'",
      "    WHEN 'VERIFICATION_REPRISE' THEN 'Une reprise a été demandée pour votre intervention.'",
      "    WHEN 'DOSSIER_CLOTURE' THEN 'Le traitement de votre signalement est terminé.'",
      "    WHEN 'DOSSIER_PRIORITE_MODIFIEE' THEN 'La priorité d’un dossier suivi par votre équipe a été modifiée.'",
      "    WHEN 'DOSSIER_LOCALISATION_MODIFIEE' THEN 'La localisation d’un dossier suivi par votre équipe a été modifiée.'",
      "    ELSE 'Une opération concernant votre espace a été mise à jour.'",
      '  END AS message',
      'FROM audit.evenement_metier AS event',
      "WHERE event.occurred_at >= NOW() - INTERVAL '90 days'",
      '  AND (',
      '    (',
      "      event.action_code IN ('SIGNALEMENT_SOUMIS', 'DEMANDE_COMPLEMENT_REPONDUE')",
      '      AND EXISTS (',
      '        SELECT 1 FROM public.utilisateur_role AS user_role',
      '        JOIN public.role AS role ON role.id_role = user_role.id_role',
      '        WHERE user_role.id_utilisateur = $1::uuid',
      "          AND role.code_role = 'AGENT_QUALIFICATION'",
      '          AND user_role.date_debut <= NOW()',
      '          AND (user_role.date_fin IS NULL OR user_role.date_fin >= NOW())',
      '      )',
      '    )',
      '    OR (',
      "      event.action_code IN ('DEMANDE_COMPLEMENT_CREEE', 'SIGNALEMENT_QUALIFIE', 'SIGNALEMENT_REJETE')",
      "      AND event.entity_type = 'SIGNALEMENT'",
      '      AND EXISTS (',
      '        SELECT 1 FROM public.signalement AS report',
      '        WHERE report.id_signalement = event.entity_id',
      '          AND report.id_utilisateur = $1::uuid',
      '      )',
      '    )',
      '    OR (',
      "      event.action_code = 'DOSSIER_CREE'",
      '      AND EXISTS (',
      '        SELECT 1 FROM public.utilisateur_role AS user_role',
      '        JOIN public.role AS role ON role.id_role = user_role.id_role',
      '        WHERE user_role.id_utilisateur = $1::uuid',
      "          AND role.code_role = 'RESPONSABLE_AFFECTATION'",
      '          AND user_role.date_debut <= NOW()',
      '          AND (user_role.date_fin IS NULL OR user_role.date_fin >= NOW())',
      '      )',
      '    )',
      '    OR (',
      "      event.action_code IN ('AFFECTATION_CREEE', 'AFFECTATION_ACCEPTEE', 'AFFECTATION_REFUSEE', 'AFFECTATION_REAFFECTEE')",
      "      AND event.entity_type = 'AFFECTATION'",
      '      AND EXISTS (',
      '        SELECT 1 FROM public.affectation AS assignment',
      '        WHERE assignment.id_affectation = event.entity_id',
      '          AND (',
      '            assignment.id_decideur = $1::uuid',
      '            OR EXISTS (',
      '              SELECT 1 FROM public.appartenance_equipe AS membership',
      '              WHERE membership.id_utilisateur = $1::uuid',
      '                AND membership.id_equipe = assignment.id_equipe',
      '                AND membership.date_debut <= NOW()',
      '                AND (membership.date_fin IS NULL OR membership.date_fin >= NOW())',
      '            )',
      '            OR EXISTS (',
      '              SELECT 1 FROM public.utilisateur_role AS user_role',
      '              JOIN public.role AS role ON role.id_role = user_role.id_role',
      '              WHERE user_role.id_utilisateur = $1::uuid',
      "                AND role.code_role = 'RESPONSABLE_AFFECTATION'",
      '                AND user_role.date_debut <= NOW()',
      '                AND (user_role.date_fin IS NULL OR user_role.date_fin >= NOW())',
      '            )',
      '          )',
      '      )',
      '    )',
      '    OR (',
      "      event.action_code IN ('DOSSIER_PRIORITE_MODIFIEE', 'DOSSIER_LOCALISATION_MODIFIEE')",
      '      AND EXISTS (',
      '        SELECT 1 FROM public.utilisateur_role AS user_role',
      '        JOIN public.role AS role ON role.id_role = user_role.id_role',
      '        WHERE user_role.id_utilisateur = $1::uuid',
      "          AND role.code_role IN ('RESPONSABLE_TRAITEMENT', 'RESPONSABLE_AFFECTATION')",
      '          AND user_role.date_debut <= NOW()',
      '          AND (user_role.date_fin IS NULL OR user_role.date_fin >= NOW())',
      '      )',
      '    )',
      '    OR (',
      "      event.action_code = 'INTERVENTION_SOUMISE'",
      '      AND EXISTS (',
      '        SELECT 1 FROM public.utilisateur_role AS user_role',
      '        JOIN public.role AS role ON role.id_role = user_role.id_role',
      '        WHERE user_role.id_utilisateur = $1::uuid',
      "          AND role.code_role = 'VERIFICATEUR_CLOTURE'",
      '          AND user_role.date_debut <= NOW()',
      '          AND (user_role.date_fin IS NULL OR user_role.date_fin >= NOW())',
      '      )',
      '    )',
      '    OR (',
      "      event.action_code IN ('VERIFICATION_CONFORME', 'VERIFICATION_REPRISE')",
      "      AND event.entity_type = 'VERIFICATION'",
      '      AND EXISTS (',
      '        SELECT 1 FROM public.verification AS verification',
      '        JOIN public.intervention AS intervention',
      '          ON intervention.id_intervention = verification.id_intervention',
      '        WHERE verification.id_verification = event.entity_id',
      '          AND (',
      '            intervention.renseigne_par = $1::uuid',
      '            OR EXISTS (',
      '              SELECT 1',
      '              FROM public.affectation AS assignment',
      '              JOIN public.appartenance_equipe AS membership',
      '                ON membership.id_equipe = assignment.id_equipe',
      '              WHERE assignment.id_affectation = intervention.id_affectation',
      '                AND membership.id_utilisateur = $1::uuid',
      '                AND membership.date_debut <= NOW()',
      '                AND (membership.date_fin IS NULL OR membership.date_fin >= NOW())',
      '            )',
      '          )',
      '      )',
      '    )',
      '    OR (',
      "      event.action_code = 'DOSSIER_CLOTURE'",
      '      AND EXISTS (',
      '        SELECT 1 FROM public.signalement AS report',
      '        WHERE report.id_dossier = event.dossier_id',
      '          AND report.id_utilisateur = $1::uuid',
      '      )',
      '    )',
      '  )',
      'ORDER BY event.occurred_at DESC, event.event_sequence DESC',
      'LIMIT $2::int',
    ].join('\n');

    return this.prisma.$queryRawUnsafe<BusinessNotification[]>(
      query,
      user.idUtilisateur,
      Math.min(100, Math.max(1, Math.floor(limit))),
    );
  }
}
